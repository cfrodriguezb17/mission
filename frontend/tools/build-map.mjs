// Natural Earth public-domain geography, distributed by world-atlas.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'),
);
const codes = {
  170: 'CO',
  '076': 'BR',
  484: 'MX',
  '032': 'AR',
  152: 'CL',
  604: 'PE',
  218: 'EC',
  858: 'UY',
  600: 'PY',
  591: 'PA',
};
const neighbors = new Set([
  '068',
  '862',
  '328',
  '740',
  '254',
  '188',
  '558',
  '340',
  '222',
  '320',
  '084',
  '192',
  '214',
  '332',
  '388',
]);
function point(coordinate) {
  const [lon, lat] = coordinate;
  return [(((lon + 120) / 90) * 520).toFixed(1), (((35 - lat) / 95) * 420).toFixed(1)];
}
function polygon(rings) {
  return rings
    .map((ring) => ring.map((p, i) => (i ? 'L' : 'M') + point(p).join(',')).join('') + 'Z')
    .join('');
}
const paths = feature(topology, topology.objects.countries)
  .features.filter((f) => codes[f.id] || neighbors.has(f.id))
  .map((f) => ({
    code: codes[f.id] ?? String(f.id),
    name: f.properties.name,
    path:
      f.geometry.type === 'Polygon'
        ? polygon(f.geometry.coordinates)
        : f.geometry.coordinates.map(polygon).join(''),
  }));
writeFileSync(
  'src/app/shared/utils/latam-paths.ts',
  '// Generated by tools/build-map.mjs. Natural Earth / world-atlas, public domain.\nexport const LATAM_PATHS = ' +
    JSON.stringify(paths, null, 2) +
    ';\n',
);
